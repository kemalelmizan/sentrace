function stripModuleToBody(filename) {
  const fullPath = path.join(srcDir, filename);
  const tsSource = fs.readFileSync(fullPath, "utf8");
  const stripped = stripTypeScriptTypes(tsSource, { mode: "strip" });

  return stripped
    // Remove multi-line and single-line relative imports
    .replace(/^\s*import\s+[\s\S]*?from\s+["']\.\/[^"']+["'];?\s*$/gm, "")
    // Remove export modifiers on top-level declarations
    .replace(/^(\s*)export\s+(async\s+function|function|class|const|let)\b/gm, "$1$2")
    // Strip trailing spaces left by erased TypeScript type annotations and interfaces
    .replace(/[ \t]+$/gm, "")
    // Collapse excessive blank lines left by stripped types/imports
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function stripReactModuleToBody() {
  const fullPath = path.join(srcDir, "react.ts");
  const tsSource = fs.readFileSync(fullPath, "utf8");
  const stripped = stripTypeScriptTypes(tsSource, { mode: "strip" });

  return stripped
    // Remove imports (replaced per ESM/CJS wrapper)
    .replace(/^\s*import\s+[\s\S]*?from\s+["'][^"']+["'];?\s*$/gm, "")
    // Remove export default at bottom (replaced per ESM/CJS wrapper)
    .replace(/^\s*export\s+default\s+SentraceReact;?\s*$/gm, "")
    // Remove export modifiers on top-level declarations
    .replace(/^(\s*)export\s+(async\s+function|function|class|const|let)\b/gm, "$1$2")
    // Strip trailing spaces left by erased TypeScript type annotations and interfaces
    .replace(/[ \t]+$/gm, "")
    // Collapse excessive blank lines left by stripped types/imports
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

